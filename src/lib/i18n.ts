/**
 * English and Hindi for everything the site says in its own voice.
 *
 * What the coach types in the dashboard — program names, prices, features,
 * method steps — is shown exactly as entered and never translated here.
 *
 * The chosen language is remembered. With no choice saved, a phone set to
 * Hindi opens in Hindi — in Devanagari, which is what that setting asks
 * for. Hinglish is always a deliberate tap.
 *
 * The Hindi is deliberately the casual tum register a coach uses on the
 * gym floor ("shuru karo", not "shuru kijiye"), which is how Robert
 * speaks to his clients.
 */

export type Lang = "en" | "hi" | "hinglish";

const LANGS: Lang[] = ["en", "hi", "hinglish"];

/** What goes in <html lang>. Hinglish is Hindi in Roman letters, which
 *  is what the "hi-Latn" subtag means — and it keeps the Devanagari
 *  font rules, which match lang="hi" exactly, off the Roman text. */
const HTML_LANG: Record<Lang, string> = {
  en: "en",
  hi: "hi",
  hinglish: "hi-Latn",
};

export function htmlLang(value: Lang) {
  return HTML_LANG[value];
}

